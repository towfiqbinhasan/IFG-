#!/usr/bin/env node
/**
 * Builds the app logo from a raster source image (e.g. a designer export / photo).
 *
 *   node scripts/build-logo.mjs [source] [left top size]
 *
 * Defaults to assets/brand/logo-source.jpg and the crop box of The Intelligence
 * Forge Lab emblem. It:
 *   1. crops the emblem to a square,
 *   2. cleans the off-white paper texture to pure white,
 *   3. writes public/brand/emblem.png (1024px master, used by the splash) and
 *      public/logo.svg (rounded white tile + embedded emblem) - the single logo
 *      file the whole app and `npm run icons` use.
 * Afterwards run:  npm run icons && npm run android:assets
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, process.argv[2] ?? "assets/brand/logo-source.jpg");
// Square crop around the emblem (in source pixels).
const [left, top, size] = process.argv.slice(3, 6).map(Number).length === 3
  ? process.argv.slice(3, 6).map(Number)
  : [478, 92, 446];

const { data, info } = await sharp(src)
  .extract({ left, top, width: size, height: size })
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

// Paper-texture cleanup: near-white, low-saturation pixels fade to pure white.
for (let i = 0; i < data.length; i += 3) {
  const r = data[i], g = data[i + 1], b = data[i + 2];
  const min = Math.min(r, g, b), max = Math.max(r, g, b);
  if (max - min < 22 && min > 196) {
    const t = Math.min(1, (min - 196) / 30);
    data[i] = r + (255 - r) * t;
    data[i + 1] = g + (255 - g) * t;
    data[i + 2] = b + (255 - b) * t;
  }
}

const clean = sharp(data, { raw: { width: info.width, height: info.height, channels: 3 } });
mkdirSync(join(root, "public/brand"), { recursive: true });

// 1024px master (lanczos upscale + light sharpen) for splash / large uses.
const master = await clean.clone().resize(1024, 1024, { kernel: "lanczos3" }).sharpen({ sigma: 0.6 }).png({ compressionLevel: 9 }).toBuffer();
writeFileSync(join(root, "public/brand/emblem.png"), master);

// 384px JPEG embed keeps logo.svg small (~40 KB); the tile is opaque white so JPEG is fine.
const embed = await sharp(master).resize(384, 384).flatten({ background: "#ffffff" }).jpeg({ quality: 90, mozjpeg: true }).toBuffer();
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- The Intelligence Forge Lab logo. Generated by scripts/build-logo.mjs from assets/brand/logo-source.jpg.
       To change the logo, replace this file (any square SVG) and run: npm run icons -->
  <defs><clipPath id="tile"><rect width="512" height="512" rx="112"/></clipPath></defs>
  <g clip-path="url(#tile)">
    <rect width="512" height="512" fill="#ffffff"/>
    <image x="20" y="20" width="472" height="472" href="data:image/jpeg;base64,${embed.toString("base64")}"/>
  </g>
</svg>
`;
writeFileSync(join(root, "public/logo.svg"), svg);
console.log(`✓ public/brand/emblem.png (1024px)\n✓ public/logo.svg (${Math.round(svg.length / 1024)} KB)`);
console.log("Next: npm run icons && npm run android:assets");
